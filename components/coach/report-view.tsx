import { CheckCircle2, ListChecks, Repeat, TriangleAlert, type LucideIcon } from "lucide-react";

import type { CoachReport } from "@/lib/ai/report-schema";

function Section({
  title,
  icon: Icon,
  tone,
  items,
}: {
  title: string;
  icon: LucideIcon;
  tone: "profit" | "loss" | "primary";
  items: { title: string; detail: string; evidence?: string }[];
}) {
  if (!items.length) return null;
  const toneClass =
    tone === "profit"
      ? "bg-profit-muted text-profit"
      : tone === "loss"
        ? "bg-loss-muted text-loss"
        : "bg-primary/10 text-primary";
  return (
    <section className="rounded-2xl surface p-5 sm:p-6">
      <h2 className="flex items-center gap-2 font-semibold">
        <span className={`flex size-7 items-center justify-center rounded-lg ${toneClass}`}>
          <Icon className="size-4" aria-hidden="true" />
        </span>
        {title}
      </h2>
      <ul className="mt-4 space-y-4">
        {items.map((it, i) => (
          <li key={i} className="border-l-2 pl-4">
            <p className="font-medium">{it.title}</p>
            <p className="mt-1 text-sm text-muted-foreground">{it.detail}</p>
            {it.evidence && (
              <p className="mt-1.5 rounded-md bg-muted/60 px-2 py-1 font-mono text-xs text-foreground/80">
                {it.evidence}
              </p>
            )}
          </li>
        ))}
      </ul>
    </section>
  );
}

/** Renders a saved report. All text is plain (React escapes it); no HTML from the model. */
export function ReportView({ report }: { report: CoachReport }) {
  return (
    <div className="space-y-4">
      <p className="rounded-2xl surface card-glow p-5 text-lg leading-relaxed font-medium sm:p-6">
        {report.headline}
      </p>
      <div className="grid gap-4 lg:grid-cols-2">
        <Section
          title="What's working"
          icon={CheckCircle2}
          tone="profit"
          items={report.whats_working}
        />
        <Section
          title="What's costing you"
          icon={TriangleAlert}
          tone="loss"
          items={report.whats_costing_you}
        />
      </div>
      <Section title="Patterns" icon={Repeat} tone="primary" items={report.patterns} />
      <section className="rounded-2xl surface card-glow p-5 sm:p-6">
        <h2 className="flex items-center gap-2 font-semibold">
          <span className="flex size-7 items-center justify-center rounded-lg bg-primary/10 text-primary">
            <ListChecks className="size-4" aria-hidden="true" />
          </span>
          Your action plan
        </h2>
        <ol className="mt-4 space-y-3">
          {report.action_plan.map((a, i) => (
            <li key={i} className="flex gap-3">
              <span className="flex size-6 shrink-0 items-center justify-center rounded-full border font-mono text-xs tabular-nums">
                {i + 1}
              </span>
              <div>
                <p className="font-medium">{a.title}</p>
                <p className="mt-0.5 text-sm text-muted-foreground">{a.detail}</p>
              </div>
            </li>
          ))}
        </ol>
      </section>
      {report.caveats.length > 0 && (
        <section className="rounded-2xl border border-dashed p-5 text-sm text-muted-foreground">
          <h2 className="font-medium text-foreground">About this data</h2>
          <ul className="mt-2 list-disc space-y-1 pl-5">
            {report.caveats.map((c, i) => (
              <li key={i}>{c}</li>
            ))}
          </ul>
        </section>
      )}
      <p className="text-xs text-muted-foreground">
        Generated by AI from your journal. Figures are calculated by TradeLedger. Not financial
        advice.
      </p>
    </div>
  );
}
